// ───────────── 生成 ─────────────
function mulberry32(a) { return function () { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
function mkShuffle(rnd) { return function (arr) { for (let i = arr.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [arr[i], arr[j]] = [arr[j], arr[i]]; } return arr; }; }

// 分两批用不同的随机种子生成：前 100 题保持与旧版完全一致（答案位置不变），
// 这样旧版数据升级时，老题的选项顺序不会被改动。
const BATCHES = [{ from: 0, to: 100, seed: 20261003 }, { from: 100, to: Q.length, seed: 20261004 }];
const out = [];
BATCHES.forEach(b => {
  const shuffle = mkShuffle(mulberry32(b.seed));
  const n = b.to - b.from;
  let slots = [];
  while (slots.length < n) slots = slots.concat([0, 1, 2, 3]);
  slots = shuffle(slots.slice(0, n));
  for (let i = b.from; i < b.to; i++) {
    const [cat, stage, q, right, w1, w2, w3, explain, flag] = Q[i];
    const wrong = shuffle([w1, w2, w3]);
    const options = [];
    let wi = 0;
    for (let k = 0; k < 4; k++) options.push(k === slots[i - b.from] ? right : wrong[wi++]);
    const o = { id: 'q' + String(i + 1).padStart(3, '0'), cat, stage, q, options, answer: slots[i - b.from], explain };
    if (flag) o.flag = true;
    out.push(o);
  }
});

// 校验
const errs = [];
const cell = {};
const seen = new Set();
out.forEach(o => {
  if (new Set(o.options).size !== 4) errs.push(o.id + ' 选项重复');
  if (seen.has(o.q)) errs.push(o.id + ' 题目重复');
  seen.add(o.q);
  if (![1, 2, 3, 4].includes(o.stage)) errs.push(o.id + ' 学段非法');
  cell[o.cat + o.stage] = (cell[o.cat + o.stage] || 0) + 1;
});
for (const c of ['文史', '理科', '通识', '二次元']) for (const l of [1, 2, 3, 4]) if ((cell[c + l] || 0) < 8) errs.push(c + l + ' 少于8题');
const pos = [0, 0, 0, 0]; out.forEach(o => pos[o.answer]++);
if (Math.max(...pos) - Math.min(...pos) > 3) errs.push('答案位置分布不均：' + pos.join('/'));
if (errs.length) { console.error('校验失败：\n' + errs.join('\n')); process.exit(1); }

